// funciones tradicionales de js

function sumar(a, b) {
  console.log(a + b);
}
sumar(5, 10);

function restar(a, b) {
  console.log(a - b);
}
restar(10, 5);

function multiplicar(a, b) {
  console.log(a * b);
}
multiplicar(5, 10);

function dividir(a, b) {
  console.log(a / b);
}
dividir(10, 5);

